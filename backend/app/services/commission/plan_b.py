logger = logging.getLogger("shopeasy.commission.plan_b")

# Direct Referral Commission (₹500.00 Gross, ₹23.34 Op Cost, ₹10.00 TDS, ₹466.66 Net)
# Credited strictly once per referred customer on their first qualifying purchase
DIRECT_GROSS_AMOUNT = Decimal("500.00")
DIRECT_OP_COST = Decimal("23.34")
DIRECT_TDS = Decimal("10.00")
DIRECT_NET_AMOUNT = Decimal("466.66")

# Generation Commission (₹50.00 Gross per eligible Billing ID to direct referring distributor)
GEN_GROSS_AMOUNT = Decimal("50.00")

# Calibration: First generation transaction in distributor's sequence
GEN_FIRST_OP_COST = Decimal("2.34")
GEN_FIRST_TDS = Decimal("1.00")
GEN_FIRST_NET_AMOUNT = Decimal("46.66")

# Calibration: Subsequent generation transactions in distributor's sequence
GEN_SUBSEQUENT_OP_COST = Decimal("2.33")
GEN_SUBSEQUENT_TDS = Decimal("1.00")
GEN_SUBSEQUENT_NET_AMOUNT = Decimal("46.67")

# Backward compatibility aliases
GEN_OP_COST = GEN_SUBSEQUENT_OP_COST
GEN_TDS = GEN_SUBSEQUENT_TDS
GEN_NET_AMOUNT = GEN_SUBSEQUENT_NET_AMOUNT

ZERO_AMOUNT = Decimal("0.00")


@dataclass
class PlanBExecutionResult:
    """Structured result of a Plan B commission processing attempt for an order."""

    order_id: int
    status: str  # "COMPLETED", "SKIPPED_NOT_PLAN_B_REFERRER", "SELF_PURCHASE_NO_COMMISSION", "UNREFERRED", "INELIGIBLE_DISTRIBUTOR", "ALREADY_PROCESSED", "FAILED"
    distributor_id: Optional[int] = None
    direct_commission_id: Optional[int] = None
    direct_net_credited: Decimal = ZERO_AMOUNT
    generation_commission_ids: List[int] = field(default_factory=list)
    generation_net_credited: Decimal = ZERO_AMOUNT
    total_net_credited: Decimal = ZERO_AMOUNT
    message: Optional[str] = None


class PlanBCommissionService:
    """Domain service managing the Plan B direct and generation commission engine."""

    @classmethod
    def process_order_commissions(
        cls,
        order_id: int,
        db: Optional[Session] = None,
        session_factory: Optional[Callable[[], Session]] = None,
        reconcile_sample_five: bool = False,
    ) -> PlanBExecutionResult:
        """Process Plan B commissions atomically.

        Enforces Confirmed Plan B Business Rules:
        - Atomic commit of commission records and wallet ledger transactions.
        - ₹500 Direct Referral Commission: Credited strictly ONCE per Plan B distributor
          across their entire lifetime (PB-DIRECT:{distributor_id}) on their first eligible referral purchase.
          Gross: ₹500.00, Op Cost: ₹23.34, TDS: ₹10.00, Net: ₹466.66.
          Subsequent customers referred by the same distributor earn ₹0 direct referral bonus.
        - ₹50 Generation Commission: Credited to the direct referring Plan B distributor for every
          eligible Billing ID generated by the purchase (PB-GEN:{billing_id.id}:{distributor_id}).
          First generation in distributor sequence: Gross ₹50.00, Op Cost ₹2.34, TDS ₹1.00, Net ₹46.66.
          Subsequent generations in distributor sequence: Gross ₹50.00, Op Cost ₹2.33, TDS ₹1.00, Net ₹46.67.
        - Single-tier: Commission credited strictly to the direct referring Plan B distributor.
          No multi-level upstream distribution.
        - Re-verification of distributor qualification & account status (RG-14, BR-X2).
        - Distributor self-purchases generate NO commission (BR-B3).
        - Cross-programme referral: Plan B distributor referring Plan A customer earns Plan B commissions.
        - Preserves BillingEngineClaim fields without modification.
        """
        if session_factory is not None:
            comm_db = session_factory()
        elif db is not None:
            comm_db = sessionmaker(bind=db.get_bind(), autocommit=False, autoflush=False)()
        else:
            comm_db = SessionLocal()

        try:
            # 1. Lock Order row
            order = (
                comm_db.query(Order)
                .filter(Order.id == order_id)
                .with_for_update()
                .first()
            )
            if not order:
                return PlanBExecutionResult(
                    order_id=order_id,
                    status="FAILED",
                    message=f"Order #{order_id} not found.",
                )

            purchaser = (
                comm_db.query(User)
                .filter(User.id == order.user_id)
                .with_for_update()
                .first()
            )
            if not purchaser:
                return PlanBExecutionResult(
                    order_id=order_id,
                    status="FAILED",
                    message=f"Purchaser #{order.user_id} not found.",
                )

            # 2. Resolve Direct Referring Distributor via applied_referral_code, purchaser.referred_by_id, or ReferralRelationship
            applied_code = order.applied_referral_code
            distributor: Optional[User] = None
            if applied_code and applied_code.strip():
                distributor = (
                    comm_db.query(User)
                    .filter(User.referral_code == applied_code.strip().upper())
                    .first()
                )

            if not distributor and purchaser.referred_by_id:
                distributor = (
                    comm_db.query(User)
                    .filter(User.id == purchaser.referred_by_id)
                    .first()
                )

            if not distributor:
                rel = (
                    comm_db.query(ReferralRelationship)
                    .filter(
                        ReferralRelationship.referee_id == purchaser.id,
                        ReferralRelationship.is_active == True,
                    )
                    .first()
                )
                if rel:
                    distributor = (
                        comm_db.query(User)
                        .filter(User.id == rel.referrer_id)
                        .first()
                    )

            if not distributor:
                if purchaser.programme != Programme.PLAN_B:
                    return PlanBExecutionResult(
                        order_id=order_id,
                        status="SKIPPED_NOT_PLAN_B",
                        message=f"Purchaser programme is '{purchaser.programme}' with no Plan B referral.",
                    )
                return PlanBExecutionResult(
                    order_id=order_id,
                    status="UNREFERRED",
                    message="No referring distributor found for this order.",
                )

            # Self-referral prohibition (BR-B3)
            if distributor.id == purchaser.id:
                return PlanBExecutionResult(
                    order_id=order_id,
                    status="SELF_PURCHASE_NO_COMMISSION",
                    message="Distributor self-purchase generates no commission (BR-B3).",
                )

            # Distributor must belong to Plan B
            if distributor.programme != Programme.PLAN_B:
                return PlanBExecutionResult(
                    order_id=order_id,
                    status="SKIPPED_NOT_PLAN_B_REFERRER",
                    distributor_id=distributor.id,
                    message=f"Distributor #{distributor.id} programme is '{distributor.programme}', not PLAN_B.",
                )

            # 3. Lock distributor's wallet to ensure concurrency-safe deduction sequence
            dist_wallet = get_or_create_wallet(
                comm_db, user_id=distributor.id, wallet_type=WalletType.DIRECT_REFERRAL
            )
            comm_db.query(Wallet).filter(Wallet.id == dist_wallet.id).with_for_update().first()

            # 4. Re-verify distributor qualification and account status at execution time (RG-14, BR-X2)
            is_eligible = True
            ineligible_reason = ""

            if not distributor.is_active or distributor.account_status == AccountStatus.DEACTIVATED:
                is_eligible = False
                ineligible_reason = "Distributor account is deactivated or inactive (RG-14)."
            elif distributor.account_status == AccountStatus.BLOCKED:
                is_eligible = False
                ineligible_reason = "Distributor account is blocked (RG-14: cannot refer or earn)."
            elif distributor.role != UserRole.CUSTOMER:
                is_eligible = False
                ineligible_reason = "Distributor has administrative role."
            else:
                # Qualifying purchase requirement (BR-X2)
                paid_purchase_count = (
                    comm_db.query(Order.id)
                    .filter(
                        Order.user_id == distributor.id,
                        Order.order_status == OrderStatus.CONFIRMED,
                        Order.payment_status == PaymentStatus.COMPLETED,
                    )
                    .count()
                )
                if paid_purchase_count == 0:
                    is_eligible = False
                    ineligible_reason = "Distributor has no qualifying confirmed paid purchase (BR-X2)."

            if not is_eligible:
                return PlanBExecutionResult(
                    order_id=order_id,
                    status="INELIGIBLE_DISTRIBUTOR",
                    distributor_id=distributor.id,
                    message=f"Distributor ineligible: {ineligible_reason}",
                )

            # 5. Fetch allocated Billing IDs for this order
            bids = (
                comm_db.query(BillingId)
                .filter(
                    BillingId.order_id == order.id,
                    BillingId.status == "ALLOCATED",
                )
                .order_by(BillingId.sequence_number.asc())
                .all()
            )
            if not bids:
                return PlanBExecutionResult(
                    order_id=order_id,
                    status="FAILED",
                    distributor_id=distributor.id,
                    message=f"No allocated Billing IDs found for Order #{order.id}.",
                )

            now = datetime.now(timezone.utc)
            direct_id: Optional[int] = None
            direct_credited = ZERO_AMOUNT
            gen_ids: List[int] = []
            gen_credited = ZERO_AMOUNT

            # 6. Part 1: Direct Referral Commission (₹500.00 Gross, ₹23.34 Op Cost, ₹10.00 TDS, ₹466.66 Net)
            # Authoritative Rule: Credited strictly ONCE PER DISTRIBUTOR across their entire lifetime.
            # Awarded on the distributor's first eligible referral purchase across all referred customers.
            # Subsequent customers referred by the same distributor earn ₹0.00 direct referral commission.
            direct_key = f"PB-DIRECT:{distributor.id}"
            legacy_direct_key = f"PB-DIRECT:{distributor.id}:{purchaser.id}"
            existing_direct = (
                comm_db.query(PlanBCommission)
                .filter(
                    (PlanBCommission.idempotency_key == direct_key)
                    | (PlanBCommission.idempotency_key == legacy_direct_key)
                    | (
                        (PlanBCommission.distributor_id == distributor.id)
                        & (PlanBCommission.commission_type == "DIRECT")
                        & (PlanBCommission.status == "EARNED")
                    )
                )
                .first()
            )

            if not existing_direct:
                try:
                    with comm_db.begin_nested():
                        direct_comm = PlanBCommission(
                            commission_type="DIRECT",
                            distributor_id=distributor.id,
                            referee_id=purchaser.id,
                            order_id=order.id,
                            billing_id=bids[0].id if bids else None,
                            gross_amount=DIRECT_GROSS_AMOUNT,
                            operational_cost_amount=DIRECT_OP_COST,
                            tds_amount=DIRECT_TDS,
                            net_amount=DIRECT_NET_AMOUNT,
                            status="EARNED",
                            idempotency_key=direct_key,
                            processed_at=now,
                        )
                        comm_db.add(direct_comm)
                        comm_db.flush()

                        # Credit wallet atomically
                        credit_wallet(
                            db=comm_db,
                            user_id=distributor.id,
                            wallet_type=WalletType.DIRECT_REFERRAL,
                            amount=DIRECT_NET_AMOUNT,
                            reference_type=WalletReferenceType.DIRECT_REFERRAL,
                            reference_id=direct_comm.id,
                            idempotency_key=direct_key,
                        )
                        direct_id = direct_comm.id
                        direct_credited = DIRECT_NET_AMOUNT
                except IntegrityError:
                    # Concurrently awarded to distributor by another competitor customer order.
                    # Savepoint rollback preserves the outer transaction, allowing this order's
                    # generation commissions to proceed without disruption.
                    logger.info(
                        f"Direct commission race detected for distributor #{distributor.id} on Order #{order.id}: "
                        "lifetime bonus already claimed concurrently. Proceeding with Generation commissions."
                    )
                    direct_id = None
                    direct_credited = ZERO_AMOUNT
            else:
                direct_id = existing_direct.id if existing_direct.order_id == order.id else None
                direct_credited = ZERO_AMOUNT

            # 7. Part 2: Generation Commission (₹50.00 Gross per eligible Billing ID to direct referring distributor)
            # Query prior EARNED generation commission count for this distributor to determine deduction calibration
            prior_gen_count = (
                comm_db.query(PlanBCommission.id)
                .filter(
                    PlanBCommission.distributor_id == distributor.id,
                    PlanBCommission.commission_type == "GENERATION",
                    PlanBCommission.status == "EARNED",
                )
                .count()
            )

            session_gen_count = 0
            for b_id in bids:
                gen_key = f"PB-GEN:{b_id.id}:{distributor.id}"
                legacy_gen_key = f"PB-GEN:{b_id.id}"
                existing_gen = (
                    comm_db.query(PlanBCommission)
                    .filter(
                        (PlanBCommission.idempotency_key == gen_key)
                        | (PlanBCommission.idempotency_key == legacy_gen_key)
                        | (
                            (PlanBCommission.distributor_id == distributor.id)
                            & (PlanBCommission.billing_id == b_id.id)
                            & (PlanBCommission.commission_type == "GENERATION")
                        )
                    )
                    .first()
                )

                if not existing_gen:
                    current_sequence_index = prior_gen_count + session_gen_count
                    if current_sequence_index == 0:
                        op_cost = GEN_FIRST_OP_COST
                        tds = GEN_FIRST_TDS
                        net = GEN_FIRST_NET_AMOUNT
                    else:
                        op_cost = GEN_SUBSEQUENT_OP_COST
                        tds = GEN_SUBSEQUENT_TDS
                        net = GEN_SUBSEQUENT_NET_AMOUNT

                    try:
                        with comm_db.begin_nested():
                            gen_comm = PlanBCommission(
                                commission_type="GENERATION",
                                distributor_id=distributor.id,
                                referee_id=purchaser.id,
                                order_id=order.id,
                                billing_id=b_id.id,
                                gross_amount=GEN_GROSS_AMOUNT,
                                operational_cost_amount=op_cost,
                                tds_amount=tds,
                                net_amount=net,
                                status="EARNED",
                                idempotency_key=gen_key,
                                processed_at=now,
                            )
                            comm_db.add(gen_comm)
                            comm_db.flush()

                            credit_wallet(
                                db=comm_db,
                                user_id=distributor.id,
                                wallet_type=WalletType.DIRECT_REFERRAL,
                                amount=net,
                                reference_type=WalletReferenceType.DIRECT_REFERRAL,
                                reference_id=gen_comm.id,
                                idempotency_key=gen_key,
                            )
                            session_gen_count += 1
                            gen_ids.append(gen_comm.id)
                            gen_credited += net
                    except IntegrityError:
                        logger.info(
                            f"Generation commission race/idempotency detected for billing_id #{b_id.id}"
                        )
                        already_gen = (
                            comm_db.query(PlanBCommission)
                            .filter(PlanBCommission.idempotency_key == gen_key)
                            .first()
                        )
                        if already_gen:
                            gen_ids.append(already_gen.id)
                else:
                    gen_ids.append(existing_gen.id)

            # 8. Atomic commit of all Plan B commission rows and wallet credits
            comm_db.commit()

            total_credited = direct_credited + gen_credited
            logger.info(
                f"Plan B commission processing completed for Order #{order.id}: "
                f"Distributor #{distributor.id} credited total ₹{total_credited} "
                f"(Direct: ₹{direct_credited}, Generation: ₹{gen_credited} across {len(bids)} units)."
            )
            return PlanBExecutionResult(
                order_id=order.id,
                status="COMPLETED",
                distributor_id=distributor.id,
                direct_commission_id=direct_id,
                direct_net_credited=direct_credited,
                generation_commission_ids=gen_ids,
                generation_net_credited=gen_credited,
                total_net_credited=total_credited,
                message="Plan B commissions processed successfully.",
            )

        except IntegrityError as exc:
            comm_db.rollback()
            logger.warning(f"IntegrityError processing Plan B commissions on Order #{order_id}: {exc}")
            return PlanBExecutionResult(
                order_id=order_id,
                status="ALREADY_PROCESSED",
                message="Commissions were already processed concurrently.",
            )
        except Exception as exc:
            comm_db.rollback()
            logger.error(f"Unexpected error processing Plan B commissions on Order #{order_id}: {exc}", exc_info=True)
            return PlanBExecutionResult(
                order_id=order_id,
                status="FAILED",
                message=str(exc),
            )
        finally:
            comm_db.close()
